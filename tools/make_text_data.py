"""Flatten Bricolage Grotesque glyph outlines into text-data.js for the 3D lettering."""
from pathlib import Path
import json
from fontTools.ttLib import TTFont
from fontTools.pens.basePen import BasePen

ROOT = Path(__file__).resolve().parents[1]
STRINGS = ['It’s a good', 'time to', 'eat well.', 'good food.', 'good mood.', 'good time.', 'clock to fit']
SEG = 7

class FlatPen(BasePen):
    def __init__(self, glyphSet):
        super().__init__(glyphSet); self.contours = []; self.cur = None
    def _moveTo(self, p): self.cur = [p]
    def _lineTo(self, p): self.cur.append(p)
    def _qCurveToOne(self, c, p):
        x0, y0 = self.cur[-1]
        for i in range(1, SEG + 1):
            t = i / SEG; u = 1 - t
            self.cur.append((u*u*x0 + 2*u*t*c[0] + t*t*p[0], u*u*y0 + 2*u*t*c[1] + t*t*p[1]))
    def _curveToOne(self, c1, c2, p):
        x0, y0 = self.cur[-1]
        for i in range(1, SEG + 1):
            t = i / SEG; u = 1 - t
            self.cur.append((u**3*x0 + 3*u*u*t*c1[0] + 3*u*t*t*c2[0] + t**3*p[0], u**3*y0 + 3*u*u*t*c1[1] + 3*u*t*t*c2[1] + t**3*p[1]))
    def _closePath(self):
        if self.cur and len(self.cur) > 2: self.contours.append(self.cur)
        self.cur = None
    _endPath = _closePath

font = TTFont(ROOT / 'assets/bricolage.ttf'); gs = font.getGlyphSet(); cmap = font.getBestCmap()
glyphs = {}
for ch in sorted(set(''.join(STRINGS))):
    if ch == ' ':
        glyphs[ch] = {'a': gs[cmap[32]].width, 'c': []}; continue
    name = cmap[ord(ch)]; pen = FlatPen(gs); gs[name].draw(pen)
    glyphs[ch] = {'a': gs[name].width, 'c': [[round(v, 1) for pt in c for v in pt] for c in pen.contours]}
data = {'upm': font['head'].unitsPerEm, 'capHeight': getattr(font['OS/2'], 'sCapHeight', 700), 'xHeight': getattr(font['OS/2'], 'sxHeight', 500), 'glyphs': glyphs}
(ROOT / 'text-data.js').write_text('/* Flattened Bricolage Grotesque outlines (SIL OFL) for 3D lettering. Generated by tools/make_text_data.py. */\nwindow.CTF_GLYPHS=' + json.dumps(data, separators=(',', ':')) + ';\n')
print(len(glyphs), 'glyphs', (ROOT / 'text-data.js').stat().st_size, 'bytes', data['capHeight'], data['xHeight'])
